"use client";

import * as React from "react";

import { defineTweaks, type TactileDemoProps } from "@/registry/lib/tweaks";
import { BendGrid } from "@/registry/ui/bend-grid";

export const tweaks = defineTweaks({
  grid: {
    kind: "range",
    label: "Grid",
    default: 6,
    min: 3,
    max: 10,
    step: 1,
  },
  strength: {
    kind: "range",
    label: "Strength",
    default: 0.6,
    min: 0,
    max: 1,
    step: 0.05,
  },
  radius: {
    kind: "range",
    label: "Radius",
    default: 170,
    min: 60,
    max: 320,
    step: 10,
    unit: "px",
  },
});

/**
 * Fieldline Gallery: a wall of its prints, generated by the component itself,
 * bends under the visitor's hand behind the opening notice.
 */
export function BendGridDemo({
  chrome = true,
  // The wall is silent: the stage's sound switch has nothing to play here.
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  sound: _sound,
  ...values
}: TactileDemoProps<typeof tweaks> & { chrome?: boolean }) {
  const [hovering, setHovering] = React.useState(false);
  const [pressed, setPressed] = React.useState(false);
  const grid = Math.round(values.grid ?? 6);

  const wall = (
    <BendGrid
      onActiveChange={setHovering}
      onPressChange={setPressed}
      className={
        chrome
          ? "h-64 rounded-3 border border-hairline"
          : "h-52 rounded-3 border border-hairline"
      }
      {...values}
    >
      <div className="flex size-full items-end p-4 sm:p-5">
        <div className="max-w-64 rounded-3 border border-hairline bg-background px-4 py-3 shadow-sm">
          <p className="font-mono text-[10px] tracking-[0.08em] text-ink-3 uppercase">
            Fieldline Gallery
          </p>
          <p className="mt-1 text-base leading-snug font-medium text-balance text-foreground">
            Forty prints, one wall
          </p>
          {chrome ? (
            <>
              <p className="mt-1 text-xs text-ink-2">Open late on Thursdays</p>
              <button
                type="button"
                className="mt-3 inline-flex h-8 items-center rounded-2 bg-primary px-3 text-xs font-medium text-primary-foreground transition-colors outline-none hover:bg-primary/90 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring focus-visible:outline-solid"
              >
                Visit the wall
              </button>
            </>
          ) : null}
        </div>
      </div>
    </BendGrid>
  );

  if (!chrome) return <div className="flex w-full">{wall}</div>;

  return (
    <div className="flex w-full max-w-2xl flex-col gap-3">
      {wall}
      <p
        role="status"
        className="border-t border-border pt-3 font-mono text-[10px] tracking-[0.08em] text-muted-foreground uppercase"
      >
        {pressed ? (
          <>
            <span className="text-signal">pressed in</span> · the tiles swell
          </>
        ) : hovering ? (
          <>
            <span className="text-signal">under your hand</span> · the wall
            bends
          </>
        ) : (
          <>
            <span className="text-signal">{grid} across</span> · resting
          </>
        )}
      </p>
    </div>
  );
}
